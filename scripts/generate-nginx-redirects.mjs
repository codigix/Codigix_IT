// Builds deploy/nginx/seo-redirects.conf from src/data/seoPages.json: an nginx
// `map` that 301-redirects old ?tab= URLs, renamed hubs and alias routes to
// their clean URL. Same rules as resolveRedirect() in src/utils/seo.js.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const seoData = JSON.parse(readFileSync(new URL('src/data/seoPages.json', root), 'utf8'));

const escapeRegex = (text) => text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

// Old links encoded tab names as "AI+Chatbots", browsers may send "AI%20Chatbots"
const tabPattern = (tab) =>
  [...tab]
    .map((ch) => {
      if (ch === ' ') return '(?:\\+|%20)';
      if (ch === '&') return '%26';
      if (ch === '(') return '(?:\\(|%28)';
      if (ch === ')') return '(?:\\)|%29)';
      return escapeRegex(ch);
    })
    .join('');

const rules = [];
for (const section of Object.values(seoData.sections)) {
  const hub = section.entries.find((entry) => entry.overview).path;
  const oldBases = [hub, ...section.legacyPaths];
  const basePattern = `(?:${oldBases.map(escapeRegex).join('|')})`;
  for (const entry of section.entries) {
    if (entry.overview && section.entries.some((e) => e.tab === entry.tab && !e.overview)) continue;
    rules.push([`^${basePattern}/?\\?(?:.*&)?tab=${tabPattern(entry.tab)}(?:&.*)?$`, entry.path]);
  }
  // Unknown tab values land on the hub
  rules.push([`^${basePattern}/?\\?(?:.*&)?tab=`, hub]);
  for (const legacy of section.legacyPaths) rules.push([`^${escapeRegex(legacy)}/?(?:\\?.*)?$`, hub]);
}
for (const [from, to] of Object.entries(seoData.redirects)) {
  rules.push([`^${escapeRegex(from)}/?(?:\\?.*)?$`, to]);
}
rules.push(['^/blogs/(?<blog_slug>[^?]+)', '/blog/$blog_slug']);

const width = Math.max(...rules.map(([pattern]) => pattern.length)) + 6;
const conf = `# Generated by scripts/generate-nginx-redirects.mjs from src/data/seoPages.json.
# Do not edit by hand: change the JSON and run \`npm run build\`.
# Include in the http {} context (e.g. at the top of the site config), then in
# the server {} block:  if ($codigix_redirect) { return 301 $codigix_redirect; }
map $request_uri $codigix_redirect {
    default "";
${rules.map(([pattern, target]) => `    ${`"~${pattern}"`.padEnd(width)} ${target};`).join('\n')}
}
`;

const outDir = new URL('deploy/nginx/', root);
mkdirSync(outDir, { recursive: true });
writeFileSync(fileURLToPath(new URL('seo-redirects.conf', outDir)), conf);
console.log(`seo-redirects.conf: ${rules.length} redirect rules`);
